// Turn the source images exported from Figma (images/*) into AVIF + WebP at a
// fixed width ladder, and write a typed manifest the <Picture> component reads.
// Static export has no image optimizer, so this replaces it.
// Usage: node scripts/images.mjs
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { root } from "./serve.mjs";

// Keep in sync with `images.imageSizes` + `images.deviceSizes` in next.config.ts,
// so every width next/image asks the loader for exists on disk.
const LADDER = [48, 96, 160, 240, 320, 480, 640, 800, 960, 1280, 1600, 1920, 2560];

const srcDir = path.join(root, "images");
const outDir = path.join(root, "public", "img");
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const manifest = {};
let bytes = 0;

for (const file of readdirSync(srcDir)
  .filter((f) => /\.(png|jpe?g|webp)$/i.test(f))
  .sort()) {
  const name = path.parse(file).name;
  const input = sharp(path.join(srcDir, file));
  const { width, height } = await input.metadata();

  const widths = LADDER.filter((w) => w < width);
  // Add the native width unless a ladder step already sits within 10% of it.
  if (!widths.length || width - widths.at(-1) > width * 0.1) widths.push(width);

  for (const w of widths) {
    const resized = input.clone().resize({ width: w, withoutEnlargement: true });
    const avif = await resized.clone().avif({ quality: 55, effort: 6 }).toBuffer();
    const webp = await resized.clone().webp({ quality: 78, effort: 6 }).toBuffer();
    writeFileSync(path.join(outDir, `${name}-${w}.avif`), avif);
    writeFileSync(path.join(outDir, `${name}-${w}.webp`), webp);
    bytes += avif.length + webp.length;
  }
  manifest[name] = { width, height, widths };
  console.log(`${name.padEnd(20)} ${width}×${height}  → ${widths.join(", ")}`);
}

const ts = `// Generated by scripts/images.mjs — do not edit by hand.
export const images = ${JSON.stringify(manifest, null, 2)} as const;

export type ImageName = keyof typeof images;
`;
writeFileSync(path.join(root, "src", "lib", "images.gen.ts"), ts);
console.log(`\n${Object.keys(manifest).length} images, ${(bytes / 1024).toFixed(0)} KB written`);
